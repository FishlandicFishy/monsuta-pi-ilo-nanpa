/** Column bytes for one character: 5 entries, bit 0 = top row. */
const COLS = {};
for (const [ch, rows] of Object.entries(G)) {
  const cols = [0, 0, 0, 0, 0];
  rows.forEach((row, r) => {
    for (let c = 0; c < 5; c++) if (row[c] === '#') cols[c] |= 1 << r;
  });
  COLS[ch] = cols;
}

const FALLBACK = COLS['?'];

/** The 5 column bytes for `ch`, or a question mark when it is not in the set. */
export function glyph(ch) {
  return COLS[ch] || FALLBACK;
}

export function hasGlyph(ch) {
  return COLS[ch] !== undefined;
}

const COMBINING_LCD_MARKS = new Set(['̄', '̂']);

/** Split text into physical LCD cells, composing supported marks over the prior glyph. */
export function lcdTextCells(text) {
  const cells = [];
  for (const ch of [...String(text || '')]) {
    if (COMBINING_LCD_MARKS.has(ch) && cells.length) cells[cells.length - 1] += ch;
    else cells.push(ch);
  }
  return cells;
}

/** One or more glyph layers drawn in the same physical LCD cell. */
export function glyphLayers(cell) {
  return [...String(cell || ' ')].map(glyph);
}

